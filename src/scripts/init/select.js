/**
 * 1. ПРОДУКТИВНІСТЬ
 * -----------------
 * - Для списків < 100 елементів - використовуйте без virtualScroll
 * - Для списків 100-1000 елементів - розгляньте пошук + сортування
 * - Для списків > 1000 елементів - обов'язково virtualScroll={true}
 */

/**
 * 2. ДОСТУПНІСТЬ (A11Y)
 * ---------------------
 * - Завжди використовуйте осмислені placeholder
 * - Для required полів завжди вказуйте errorRequired
 * - Селект підтримує клавіатурну навігацію:
 *   - Enter/Space - відкрити/закрити
 *   - Arrow Up/Down - навігація по опціях
 *   - Escape - закрити dropdown
 */

/**
 * 3. ВАЛІДАЦІЯ
 * ------------
 * - required працює з HTML5 валідацією форм
 * - Інтегрується з вашим FormValidator
 * - Можна використовувати з будь-якою бібліотекою валідації
 */

/**
 * 4. СТИЛІЗАЦІЯ
 * -------------
 * - Всі стилі в custom-select.scss
 * - Використовує CSS класи для станів (error, success, disabled)
 * - Легко змінити кольори та розміри через SCSS змінні
 */

/**
 * 5. BROWSER STORAGE
 * ------------------
 * - НЕ використовує localStorage або sessionStorage
 * - Всі дані зберігаються в пам'яті під час сесії
 * - Для збереження стану між перезавантаженнями - використовуйте форми
 */

