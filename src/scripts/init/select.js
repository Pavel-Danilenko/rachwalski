/**
 * CustomSelect - Повнофункціональний кастомний селект
 * JS тільки керує логікою, весь HTML в Astro
 */

/**
 * ============================================================================
 * CUSTOM SELECT - ПОВНА ДОКУМЕНТАЦІЯ
 * ============================================================================
 *
 * Повнофункціональний кастомний селект з підтримкою всіх можливостей
 *
 * БАЗОВЕ ВИКОРИСТАННЯ:
 * --------------------
 * <Select
 *    name="country"
 *    options={countryOptions}
 *    placeholder="Оберіть країну"
 * />
 *
 * ============================================================================
 * АТРИБУТИ ТА ЇХ ОПИС
 * ============================================================================
 */

/**
 * 1. name (обов'язковий)
 * ----------------------
 * Тип: string
 * Обов'язковий: ТАК
 *
 * Назва поля для form submission. Буде використано як атрибут name в прихованому <select>.
 *
 * Приклад:
 * name="country"
 * name="user_role"
 * name="categories[]"  // для множинного вибору
 */

/**
 * 2. options (обов'язковий)
 * -------------------------
 * Тип: Option[] | OptionGroup[]
 * Обов'язковий: ТАК
 *
 * Масив опцій або груп опцій для відображення в селекті.
 *
 * ФОРМАТ ПРОСТОЇ ОПЦІЇ:
 * {
 *    value: string,         // Значення, яке буде відправлено в формі
 *    label: string,         // Текст, який буде відображено користувачу
 *    description?: string,  // Опціональний підпис під опцією
 *    disabled?: boolean,    // Чи можна вибрати цю опцію
 *    icon?: string         // Іконка (зараз не використовується, зарезервовано)
 * }
 *
 * ФОРМАТ ГРУПИ:
 * {
 *    group: string,         // Назва групи
 *    items: Option[]        // Масив опцій в групі
 * }
 *
 * Приклади:
 *
 * // Прості опції
 * options={[
 *    { value: "ua", label: "Україна" },
 *    { value: "pl", label: "Польща" },
 *    { value: "de", label: "Німеччина", disabled: true }
 * ]}
 *
 * // Опції з описами
 * options={[
 *    {
 *       value: "basic",
 *       label: "Basic Plan",
 *       description: "$9/місяць - Базові функції"
 *    },
 *    {
 *       value: "pro",
 *       label: "Pro Plan",
 *       description: "$29/місяць - Всі функції"
 *    }
 * ]}
 *
 * // Групи
 * options={[
 *    {
 *       group: "Європа",
 *       items: [
 *          { value: "ua", label: "Україна" },
 *          { value: "pl", label: "Польща" }
 *       ]
 *    },
 *    {
 *       group: "Азія",
 *       items: [
 *          { value: "jp", label: "Японія" },
 *          { value: "kr", label: "Корея" }
 *       ]
 *    }
 * ]}
 */

/**
 * 3. placeholder
 * --------------
 * Тип: string
 * За замовчуванням: "Оберіть варіант"
 *
 * Текст, який відображається коли нічого не вибрано.
 *
 * Приклад:
 * placeholder="Виберіть вашу країну"
 * placeholder="-- Не вибрано --"
 */

/**
 * 4. required
 * -----------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Чи є поле обов'язковим для заповнення. Працює з HTML5 валідацією форм.
 *
 * Приклад:
 * required={true}
 */

/**
 * 5. searchable
 * -------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Додає поле пошуку всередині dropdown для фільтрації опцій.
 * Пошук працює по label та description опцій.
 *
 * Приклад:
 * searchable={true}
 */

/**
 * 6. searchPlaceholder
 * --------------------
 * Тип: string
 * За замовчуванням: "Пошук..."
 *
 * Placeholder для поля пошуку (працює тільки якщо searchable={true}).
 *
 * Приклад:
 * searchPlaceholder="Шукати країну..."
 * searchPlaceholder="Введіть назву..."
 */

/**
 * 7. searchClearable
 * ------------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Додає кнопку очищення (хрестик) в полі пошуку.
 * Працює тільки якщо searchable={true}.
 *
 * Приклад:
 * searchable={true}
 * searchClearable={true}
 */

/**
 * 8. multiple
 * -----------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Дозволяє вибирати кілька опцій одночасно.
 * Змінює поведінку селекта: dropdown не закривається після вибору.
 *
 * Приклад:
 * multiple={true}
 */

/**
 * 9. multipleSelectedText
 * -----------------------
 * Тип: string
 * За замовчуванням: "Вибрано:"
 *
 * Текст, який відображається перед кількістю вибраних елементів.
 * Працює тільки якщо multiple={true} і вибрано більше ніж multipleDisplayLimit.
 *
 * Приклад:
 * multipleSelectedText="Selected:"
 * multipleSelectedText="Вибрано елементів:"
 *
 * Результат:
 * "Вибрано: 5"
 */

/**
 * 10. multipleDisplayLimit
 * ------------------------
 * Тип: number
 * За замовчуванням: 2
 *
 * Скільки вибраних елементів показувати повністю перед тим,
 * як перейти до формату "Вибрано: X".
 *
 * Приклади:
 * multipleDisplayLimit={2}  // "Україна, Польща" або "Вибрано: 3"
 * multipleDisplayLimit={5}  // "A, B, C, D, E" або "Вибрано: 6"
 * multipleDisplayLimit={0}  // Завжди показувати "Вибрано: X"
 */

/**
 * 11. showRemovableTags
 * ---------------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Відображає вибрані елементи як теги з кнопкою видалення (хрестик).
 * Працює тільки якщо multiple={true}.
 * ВАЖЛИВО: Якщо true, multipleDisplayLimit ігнорується.
 *
 * Приклад:
 * multiple={true}
 * showRemovableTags={true}
 *
 * Результат:
 * [Україна X] [Польща X] [Німеччина X]
 */

/**
 * 12. showSelectAll
 * -----------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Додає кнопку "Вибрати всі" / "Скасувати все" вгорі dropdown.
 * Працює тільки якщо multiple={true}.
 * Автоматично змінює текст залежно від стану.
 *
 * Приклад:
 * multiple={true}
 * showSelectAll={true}
 */

/**
 * 13. selectAllText
 * -----------------
 * Тип: string
 * За замовчуванням: "Вибрати всі"
 *
 * Текст кнопки коли не всі елементи вибрані.
 * Працює тільки якщо showSelectAll={true}.
 *
 * Приклад:
 * selectAllText="Select All"
 * selectAllText="Вибрати все"
 */

/**
 * 14. deselectAllText
 * -------------------
 * Тип: string
 * За замовчуванням: "Скасувати все"
 *
 * Текст кнопки коли всі елементи вибрані.
 * Працює тільки якщо showSelectAll={true}.
 *
 * Приклад:
 * deselectAllText="Deselect All"
 * deselectAllText="Очистити вибір"
 */

/**
 * 15. showClearButton
 * -------------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Додає кнопку очищення (хрестик) праворуч від стрілки в тригері.
 * Кнопка з'являється тільки коли щось вибрано.
 * Працює як для одиночного, так і для множинного вибору.
 *
 * Приклад:
 * showClearButton={true}
 */

/**
 * 16. clearButtonText
 * -------------------
 * Тип: string
 * За замовчуванням: "Очистити"
 *
 * Текст підказки (title) для кнопки очищення.
 * Працює тільки якщо showClearButton={true}.
 *
 * Приклад:
 * clearButtonText="Clear selection"
 * clearButtonText="Скасувати вибір"
 */

/**
 * 17. noResultsText
 * -----------------
 * Тип: string
 * За замовчуванням: "Нічого не знайдено"
 *
 * Текст, який відображається коли пошук не знайшов жодної опції.
 * Працює тільки якщо searchable={true}.
 *
 * Приклад:
 * noResultsText="No results found"
 * noResultsText="Результатів немає"
 */

/**
 * 18. highlightSearch
 * -------------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Підсвічує знайдений текст в опціях жовтим кольором.
 * Працює тільки якщо searchable={true}.
 *
 * Приклад:
 * searchable={true}
 * highlightSearch={true}
 *
 * Пошук: "укр"
 * Результат: У͟к͟р͟аїна (підсвічено)
 */

/**
 * 19. sortAlphabetically
 * ----------------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Автоматично сортує опції за алфавітом (за label).
 * Якщо використовуються групи, сортує опції всередині кожної групи окремо.
 *
 * Приклад:
 * sortAlphabetically={true}
 */

/**
 * 20. virtualScroll
 * -----------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Увімкнути віртуальний скрол для ВЕЛИКИХ списків (1000+ елементів).
 * Рендерить тільки видимі елементи, що значно покращує продуктивність.
 * ВАЖЛИВО: Всі опції повинні мати однакову висоту.
 *
 * Приклад:
 * virtualScroll={true}
 * itemHeight={40}  // обов'язково вказати висоту
 */

/**
 * 21. itemHeight
 * --------------
 * Тип: number
 * За замовчуванням: 40
 *
 * Висота одного елемента в пікселях для віртуального скролу.
 * Працює тільки якщо virtualScroll={true}.
 * Всі елементи ПОВИННІ мати однакову висоту!
 *
 * Приклад:
 * virtualScroll={true}
 * itemHeight={50}  // якщо ваші опції вищі
 */

/**
 * 22. defaultValue
 * ----------------
 * Тип: string | string[]
 *
 * Значення за замовчуванням.
 * Для одиночного вибору - string.
 * Для множинного вибору - string[].
 *
 * Приклади:
 * defaultValue="ua"              // одиночний вибір
 * defaultValue={["ua", "pl"]}    // множинний вибір
 */

/**
 * 23. errorRequired
 * -----------------
 * Тип: string
 *
 * Текст помилки валідації, який відображається якщо поле required і не заповнене.
 *
 * Приклад:
 * required={true}
 * errorRequired="Будь ласка, оберіть країну"
 * errorRequired="This field is required"
 */

/**
 * 24. disabled
 * ------------
 * Тип: boolean
 * За замовчуванням: false
 *
 * Повністю вимикає селект. Користувач не може його відкрити або змінити.
 *
 * Приклад:
 * disabled={true}
 */

/**
 * 25. maxSelections
 * -----------------
 * Тип: number
 *
 * Максимальна кількість елементів, які можна вибрати.
 * Працює тільки якщо multiple={true}.
 * Якщо досягнуто ліміт, селект тряситься при спробі вибрати ще.
 *
 * Приклади:
 * multiple={true}
 * maxSelections={3}   // можна вибрати максимум 3 елементи
 * maxSelections={10}
 *
 * Також відображає лічильник: "2 / 3"
 */

