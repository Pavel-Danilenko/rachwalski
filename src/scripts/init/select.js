class CustomSelect {
   constructor(wrapper) {
      this.wrapper = wrapper;
      this.formGroup = wrapper.closest(".form-group");
      this.selectElement = wrapper.querySelector(".hidden-select");
      this.customSelect = wrapper.querySelector(".custom-select");
      this.trigger = wrapper.querySelector(".custom-select__trigger");

      if (!this.selectElement || !this.customSelect || !this.trigger) {
         console.error("CustomSelect: Missing required elements", {
            wrapper,
            selectElement: this.selectElement,
            customSelect: this.customSelect,
            trigger: this.trigger,
         });
         return;
      }

      this.valueDisplay = wrapper.querySelector(".custom-select__value");
      this.dropdown = wrapper.querySelector(".custom-select__dropdown");
      this.optionsContainer = wrapper.querySelector(
         ".custom-select__options-container",
      );
      this.optionsList = wrapper.querySelector(".custom-select__options");
      this.options = Array.from(
         wrapper.querySelectorAll(".custom-select__option"),
      );
      this.groupLabels = Array.from(
         wrapper.querySelectorAll(".custom-select__group-label"),
      );
      this.searchInput = wrapper.querySelector(".custom-select__search-input");
      this.searchClearBtn = wrapper.querySelector(
         ".custom-select__search-clear",
      );
      this.counter = wrapper.querySelector(".custom-select__counter");
      this.counterText = wrapper.querySelector(".custom-select__counter-text");
      this.clearButton = wrapper.querySelector(".custom-select__clear-button");
      this.selectAllBtn = wrapper.querySelector(
         ".custom-select__select-all-btn",
      );
      this.noResults = wrapper.querySelector(".custom-select__no-results");
      this.tagTemplate = wrapper.parentElement?.querySelector(
         ".custom-select__tag-template",
      );

      this.isOpen = false;
      this.isMultiple = this.customSelect.dataset.multiple === "true";
      this.isSearchable = this.customSelect.dataset.searchable === "true";
      this.isDisabled = this.customSelect.dataset.disabled === "true";
      this.maxSelections = parseInt(
         this.selectElement.dataset.maxSelections || "0",
      );
      this.selectedValues = [];
      this.placeholder =
         this.valueDisplay?.dataset.placeholder ||
         this.valueDisplay?.textContent ||
         "Оберіть варіант";
      this.focusedIndex = -1;

      this.displayLimit = parseInt(
         this.customSelect.dataset.displayLimit || "2",
      );
      this.showRemovableTags =
         this.customSelect.dataset.removableTags === "true";
      this.highlightSearch =
         this.customSelect.dataset.highlightSearch === "true";
      this.virtualScroll = this.customSelect.dataset.virtualScroll === "true";
      this.itemHeight = parseInt(this.customSelect.dataset.itemHeight || "40");

      this.allSelectableOptions = this.options.filter(
         (opt) => opt.dataset.disabled !== "true",
      );
      this.currentSearchTerm = "";
      this.searchDebounce = null;
      this.enableGroupSelection =
         this.customSelect.dataset.enableGroupSelection === "true";
      this.lastValidationState = null; // ✅ Запам'ятовуємо останній стан валідації

      this.init();
   }

   init() {
      if (this.isDisabled) return;

      this.setDefaultValues();
      this.updateClearButton();
      this.updateSelectAllButton();
      this.updateCounter();
      this.setupAriaAttributes();

      this.trigger.addEventListener(
         "touchstart",
         (e) => {
            if (e.target.closest(".custom-select__tag-remove")) {
               return;
            }
            if (e.target.closest(".custom-select__clear-button")) {
               e.stopPropagation();
               this.clearAll();
               return;
            }
            e.preventDefault();
            this.toggle();
         },
         { passive: false },
      );

      this.trigger.addEventListener("click", (e) => {
         if (e.target.closest(".custom-select__tag-remove")) {
            return;
         }
         if (e.target.closest(".custom-select__clear-button")) {
            e.stopPropagation();
            this.clearAll();
            return;
         }
         this.toggle();
      });

      this.options.forEach((option, index) => {
         option.addEventListener("click", (e) => {
            if (option.dataset.disabled === "true") {
               return;
            }
            this.selectOption(e);
         });
         option.addEventListener("mouseenter", () => {
            this.focusedIndex = index;
            this.updateFocusedOption();
         });
      });

      if (this.isMultiple && this.enableGroupSelection) {
         this.groupLabels.forEach((groupLabel) => {
            groupLabel.addEventListener("click", (e) => {
               e.stopPropagation();
               this.selectGroup(groupLabel);
            });
            groupLabel.addEventListener("keydown", (e) => {
               if (e.key === "Enter" || e.key === " ") {
                  e.preventDefault();
                  this.selectGroup(groupLabel);
               }
            });
         });
      }

      if (this.selectAllBtn) {
         this.selectAllBtn.addEventListener("click", (e) => {
            e.stopPropagation();
            this.toggleSelectAll();
         });
      }

      if (this.clearButton) {
         this.clearButton.addEventListener("click", (e) => {
            e.stopPropagation();
            this.clearAll();
         });
      }

      if (this.searchInput) {
         this.searchInput.addEventListener("input", (e) => {
            clearTimeout(this.searchDebounce);
            this.searchDebounce = setTimeout(() => {
               this.currentSearchTerm = e.target.value;
               this.handleSearch(e);
               this.updateSearchClearButton();
            }, 300);
         });
         this.searchInput.addEventListener("keydown", (e) =>
            this.handleSearchKeyboard(e),
         );

         if (this.searchClearBtn) {
            this.searchClearBtn.addEventListener("click", (e) => {
               e.stopPropagation();
               this.clearSearch();
            });
         }
      }

      document.addEventListener("click", (e) => this.handleOutsideClick(e));

      this.trigger.addEventListener("keydown", (e) => this.handleKeyboard(e));

      this.selectElement.addEventListener(
         "blur",
         (e) => {
            if (this.isOpen) {
               e.stopImmediatePropagation();
            }
         },
         true,
      );

      window.addEventListener(
         "scroll",
         () => {
            if (this.isOpen) {
               this.updateDropdownPosition();
            }
         },
         true,
      );

      window.addEventListener("resize", () => {
         if (this.isOpen) {
            this.updateDropdownPosition();
         }
      });

      if (this.virtualScroll) {
         this.initVirtualScroll();
      }
   }

   setupAriaAttributes() {
      const dropdownId = `dropdown-${Math.random().toString(36).substr(2, 9)}`;
      this.dropdown.id = dropdownId;
      this.trigger.setAttribute("aria-controls", dropdownId);
      this.trigger.setAttribute("aria-expanded", "false");

      if (this.isMultiple) {
         this.trigger.setAttribute("aria-multiselectable", "true");
      }
   }

   validateSelection() {
      if (!this.selectElement.required) return true;

      const isValid = this.selectedValues.length > 0;

      // ✅ Якщо стан не змінився - не міняємо UI
      if (this.lastValidationState === isValid) {
         return isValid;
      }

      this.lastValidationState = isValid;

      if (!isValid) {
         this.customSelect.classList.add("has-error");

         const errorMessage = this.selectElement.dataset.errorRequired;
         if (errorMessage && this.formGroup) {
            let errorElement = this.formGroup.querySelector(".error-message");
            if (errorElement) {
               errorElement.textContent = errorMessage;
               errorElement.style.display = "block";
            }
         }
      } else {
         this.customSelect.classList.remove("has-error");

         if (this.formGroup) {
            let errorElement = this.formGroup.querySelector(".error-message");
            if (errorElement) {
               errorElement.style.display = "none";
            }
         }
      }

      return isValid;
   }

   setDefaultValues() {
      const selectedOptions = Array.from(
         this.selectElement.querySelectorAll("option:checked"),
      );

      if (selectedOptions.length > 0 && selectedOptions[0].value !== "") {
         selectedOptions.forEach((option) => {
            this.selectedValues.push(option.value);
            const customOption = this.options.find(
               (opt) => opt.dataset.value === option.value,
            );
            if (customOption) {
               customOption.classList.add("selected");
            }
         });
         this.updateDisplay();
         this.updateCounter();
         this.updateSelectAllButton();
      }
   }

   toggle() {
      if (this.isOpen) {
         this.close();
      } else {
         this.open();
      }
   }

   open() {
      this.isOpen = true;
      this.customSelect.classList.add("is-open");
      this.dropdown.style.display = "flex";

      this.trigger.setAttribute("aria-expanded", "true");

      this.updateDropdownPosition();

      requestAnimationFrame(() => {
         this.dropdown.classList.add("is-visible");
      });

      if (this.searchInput) {
         setTimeout(() => this.searchInput.focus(), 100);
      }

      const selectedOption = this.optionsList.querySelector(".selected");
      if (selectedOption) {
         selectedOption.scrollIntoView({
            block: "center",
            behavior: "smooth",
         });
         this.focusedIndex = this.options.indexOf(selectedOption);
      } else {
         this.focusedIndex = 0;
      }
      this.updateFocusedOption();
   }

   updateDropdownPosition() {
      const triggerRect = this.trigger.getBoundingClientRect();
      const spaceBelow = window.innerHeight - triggerRect.bottom;
      const spaceAbove = triggerRect.top;

      const maxHeightSetting =
         this.customSelect.dataset.maxDropdownHeight || "80vh";
      const maxHeightPx = maxHeightSetting.includes("vh")
         ? (window.innerHeight * parseInt(maxHeightSetting)) / 100
         : parseInt(maxHeightSetting);

      const dropdownHeight = this.dropdown.offsetHeight || maxHeightPx;

      this.customSelect.classList.remove("open-upward", "open-downward");

      if (spaceBelow < dropdownHeight && spaceAbove > dropdownHeight) {
         this.customSelect.classList.add("open-upward");
      } else {
         this.customSelect.classList.add("open-downward");
      }

      const maxHeight = Math.max(spaceBelow, spaceAbove) - 20;
      this.dropdown.style.maxHeight = `${Math.min(maxHeight, maxHeightPx)}px`;
   }

   close() {
      this.isOpen = false;
      this.customSelect.classList.remove("is-open");
      this.dropdown.classList.remove("is-visible");

      this.trigger.setAttribute("aria-expanded", "false");

      setTimeout(() => {
         if (!this.isOpen) {
            this.dropdown.style.display = "none";
            this.dropdown.style.maxHeight = "";
            this.customSelect.classList.remove("open-upward", "open-downward");
         }
      }, 300);

      if (this.searchInput) {
         this.clearSearch();
      }

      this.focusedIndex = -1;
      this.updateFocusedOption();

      const event = new Event("blur", { bubbles: true });
      this.selectElement.dispatchEvent(event);
   }

   selectOption(e) {
      const option = e.currentTarget;
      const value = option.dataset.value;

      if (option.dataset.disabled === "true") {
         return;
      }

      if (this.isMultiple) {
         if (this.selectedValues.includes(value)) {
            this.selectedValues = this.selectedValues.filter(
               (v) => v !== value,
            );
            option.classList.remove("selected");
         } else {
            if (
               this.maxSelections > 0 &&
               this.selectedValues.length >= this.maxSelections
            ) {
               this.showMaxSelectionsWarning();
               return;
            }

            this.selectedValues.push(value);
            option.classList.add("selected");
         }

         this.updateCounter();
         this.updateSelectAllButton();
      } else {
         this.options.forEach((opt) => opt.classList.remove("selected"));
         option.classList.add("selected");
         this.selectedValues = [value];
         this.close();
      }

      this.updateSelect();
      this.updateDisplay();
      this.updateClearButton();
      this.validateSelection();
   }

   removeValue(value) {
      this.selectedValues = this.selectedValues.filter((v) => v !== value);

      const option = this.options.find((opt) => opt.dataset.value === value);
      if (option) {
         option.classList.remove("selected");
      }

      this.updateSelect();
      this.updateDisplay();
      this.updateCounter();
      this.updateClearButton();
      this.updateSelectAllButton();
      this.validateSelection();
   }

   clearAll() {
      this.selectedValues = [];
      this.options.forEach((opt) => opt.classList.remove("selected"));

      this.updateSelect();
      this.updateDisplay();
      this.updateCounter();
      this.updateClearButton();
      this.updateSelectAllButton();
      this.validateSelection();
   }

   toggleSelectAll() {
      const hasMax = this.selectAllBtn.dataset.hasMax === "true";

      if (hasMax) {
         this.clearAll();
         return;
      }

      const allSelected = this.allSelectableOptions.every((opt) =>
         this.selectedValues.includes(opt.dataset.value),
      );

      if (allSelected) {
         this.allSelectableOptions.forEach((opt) => {
            const value = opt.dataset.value;
            this.selectedValues = this.selectedValues.filter(
               (v) => v !== value,
            );
            opt.classList.remove("selected");
         });
      } else {
         this.allSelectableOptions.forEach((opt) => {
            const value = opt.dataset.value;
            if (!this.selectedValues.includes(value)) {
               this.selectedValues.push(value);
               opt.classList.add("selected");
            }
         });
      }

      this.updateSelect();
      this.updateDisplay();
      this.updateCounter();
      this.updateClearButton();
      this.updateSelectAllButton();
      this.validateSelection();
   }

   selectGroup(groupLabel) {
      const groupName = groupLabel.textContent.trim();
      const groupOptions = this.options.filter(
         (opt) =>
            opt.dataset.group === groupName && opt.dataset.disabled !== "true",
      );

      if (!this.isMultiple) return;

      const allGroupSelected = groupOptions.every((opt) =>
         this.selectedValues.includes(opt.dataset.value),
      );

      if (allGroupSelected) {
         groupOptions.forEach((opt) => {
            const value = opt.dataset.value;
            this.selectedValues = this.selectedValues.filter(
               (v) => v !== value,
            );
            opt.classList.remove("selected");
         });
      } else {
         groupOptions.forEach((opt) => {
            const value = opt.dataset.value;
            if (!this.selectedValues.includes(value)) {
               if (
                  this.maxSelections === 0 ||
                  this.selectedValues.length < this.maxSelections
               ) {
                  this.selectedValues.push(value);
                  opt.classList.add("selected");
               }
            }
         });
      }

      this.updateSelect();
      this.updateDisplay();
      this.updateCounter();
      this.updateClearButton();
      this.updateSelectAllButton();
      this.validateSelection();
   }

   updateSelectAllButton() {
      if (!this.selectAllBtn) return;

      const hasMax = this.selectAllBtn.dataset.hasMax === "true";
      const hasSelected = this.selectedValues.length > 0;

      if (hasMax) {
         const clearAllText = this.selectAllBtn.dataset.clearAllText;
         this.selectAllBtn.textContent = clearAllText;

         if (!hasSelected) {
            this.selectAllBtn.disabled = true;
            this.selectAllBtn.classList.add("is-disabled");
         } else {
            this.selectAllBtn.disabled = false;
            this.selectAllBtn.classList.remove("is-disabled");
         }
         return;
      }

      const allSelected = this.allSelectableOptions.every((opt) =>
         this.selectedValues.includes(opt.dataset.value),
      );

      const selectText = this.selectAllBtn.dataset.selectText;
      const deselectText = this.selectAllBtn.dataset.deselectText;

      this.selectAllBtn.textContent = allSelected ? deselectText : selectText;

      this.selectAllBtn.disabled = false;
      this.selectAllBtn.classList.remove("is-disabled");
   }

   updateClearButton() {
      if (!this.clearButton) return;

      const isEnabled = this.clearButton.dataset.enabled === "true";
      if (!isEnabled) {
         this.clearButton.style.display = "none";
         return;
      }

      if (this.selectedValues.length > 0) {
         this.clearButton.style.display = "flex";
      } else {
         this.clearButton.style.display = "none";
      }
   }

   updateSearchClearButton() {
      if (!this.searchClearBtn) return;

      if (this.searchInput.value.length > 0) {
         this.searchClearBtn.style.display = "flex";
      } else {
         this.searchClearBtn.style.display = "none";
      }
   }

   clearSearch() {
      if (!this.searchInput) return;

      this.searchInput.value = "";
      this.currentSearchTerm = "";
      this.options.forEach((opt) => {
         opt.style.display = "";
         if (this.highlightSearch) {
            const textElement = opt.querySelector(
               ".custom-select__option-text",
            );
            if (textElement) {
               const originalText =
                  opt.dataset.label || textElement.textContent;
               textElement.textContent = originalText;
            }
         }
      });
      this.updateSearchClearButton();
      this.hideNoResults();
   }

   updateSelect() {
      if (this.isMultiple) {
         Array.from(this.selectElement.options).forEach((option) => {
            option.selected = this.selectedValues.includes(option.value);
         });
      } else {
         this.selectElement.value = this.selectedValues[0] || "";
      }

      const event = new Event("change", { bubbles: true });
      this.selectElement.dispatchEvent(event);

      const event2 = new Event("input", { bubbles: true });
      this.selectElement.dispatchEvent(event2);
   }

   updateDisplay() {
      if (this.selectedValues.length === 0) {
         this.valueDisplay.textContent = this.placeholder;
         this.valueDisplay.innerHTML = this.placeholder;
         this.customSelect.classList.remove("has-value");
         return;
      }

      const selectedItems = this.selectedValues
         .map((value) => {
            const option = this.options.find(
               (opt) => opt.dataset.value === value,
            );
            return {
               value: value,
               label:
                  option?.dataset.label ||
                  option?.querySelector(".custom-select__option-text")
                     ?.textContent ||
                  "",
            };
         })
         .filter((item) => item.label);

      if (this.isMultiple) {
         if (this.showRemovableTags && this.tagTemplate) {
            this.valueDisplay.innerHTML = "";

            selectedItems.forEach((item) => {
               const tagContent = this.tagTemplate.content.cloneNode(true);
               const tag = tagContent.querySelector(".custom-select__tag");
               const textSpan = tag.querySelector(".custom-select__tag-text");
               const removeBtn = tag.querySelector(
                  ".custom-select__tag-remove",
               );

               textSpan.textContent = item.label;
               removeBtn.dataset.value = item.value;
               removeBtn.setAttribute("aria-label", `Видалити ${item.label}`);

               removeBtn.addEventListener("click", (e) => {
                  e.stopPropagation();
                  this.removeValue(item.value);
               });

               this.valueDisplay.appendChild(tag);
            });
         } else {
            if (selectedItems.length > this.displayLimit) {
               const multipleText =
                  this.customSelect.dataset.multipleText || "Вибрано:";
               this.valueDisplay.textContent = `${multipleText} ${selectedItems.length}`;
            } else {
               this.valueDisplay.textContent = selectedItems
                  .map((item) => item.label)
                  .join(", ");
            }
         }
      } else {
         this.valueDisplay.textContent = selectedItems[0].label;
      }

      this.customSelect.classList.add("has-value");
   }

   updateCounter() {
      if (!this.counter || !this.counterText) return;

      const showCounter = this.counter.dataset.showCounter === "true";
      const selected = this.selectedValues.length;
      const total = this.allSelectableOptions.length;

      if (this.maxSelections > 0) {
         const remaining = this.maxSelections - selected;
         const textSelected = this.counter.dataset.textSelected;
         const textOf = this.counter.dataset.textOf;
         const textRemaining = this.counter.dataset.textRemaining;
         const textLimit = this.counter.dataset.textLimit;

         this.counterText.textContent = `${textSelected} ${selected} ${textOf} ${total} | ${textLimit}: ${this.maxSelections} (${textRemaining}: ${remaining})`;
      } else if (showCounter) {
         const textSelected = this.counter.dataset.textSelected;
         const textOf = this.counter.dataset.textOf;

         this.counterText.textContent = `${textSelected} ${selected} ${textOf} ${total}`;
      }
   }

   showMaxSelectionsWarning() {
      this.customSelect.classList.add("max-selections-reached");

      setTimeout(() => {
         this.customSelect.classList.remove("max-selections-reached");
      }, 500);
   }

   handleSearch(e) {
      const searchTerm = e.target.value.toLowerCase();
      let hasVisibleOptions = false;

      this.options.forEach((option) => {
         const text = (
            option.dataset.label ||
            option.querySelector(".custom-select__option-text")?.textContent ||
            ""
         ).toLowerCase();
         const description =
            option
               .querySelector(".custom-select__option-description")
               ?.textContent?.toLowerCase() || "";

         if (text.includes(searchTerm) || description.includes(searchTerm)) {
            option.style.display = "";
            hasVisibleOptions = true;

            if (this.highlightSearch && searchTerm) {
               const textElement = option.querySelector(
                  ".custom-select__option-text",
               );
               if (textElement) {
                  const originalText =
                     option.dataset.label || textElement.textContent;
                  const regex = new RegExp(
                     `(${this.escapeRegex(searchTerm)})`,
                     "gi",
                  );
                  textElement.innerHTML = originalText.replace(
                     regex,
                     '<mark class="custom-select__highlight">$1</mark>',
                  );
               }
            }
         } else {
            option.style.display = "none";

            if (this.highlightSearch) {
               const textElement = option.querySelector(
                  ".custom-select__option-text",
               );
               if (textElement) {
                  textElement.textContent =
                     option.dataset.label || textElement.textContent;
               }
            }
         }
      });

      if (!hasVisibleOptions) {
         this.showNoResults();
      } else {
         this.hideNoResults();
      }

      const visibleOptions = this.options.filter(
         (opt) => opt.style.display !== "none",
      );
      if (visibleOptions.length > 0) {
         this.focusedIndex = this.options.indexOf(visibleOptions[0]);
         this.updateFocusedOption();
      }
   }

   showNoResults() {
      if (this.noResults) {
         this.optionsList.style.display = "none";
         this.noResults.style.display = "flex";
      }
   }

   hideNoResults() {
      if (this.noResults) {
         this.optionsList.style.display = "";
         this.noResults.style.display = "none";
      }
   }

   escapeRegex(string) {
      return string.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
   }

   initVirtualScroll() {
      if (!this.virtualScroll || this.options.length < 50) return;

      const containerHeight = 300;
      const totalHeight = this.options.length * this.itemHeight;

      this.optionsList.style.height = `${totalHeight}px`;
      this.optionsList.style.position = "relative";

      let scrollTop = 0;

      this.optionsContainer.addEventListener("scroll", () => {
         scrollTop = this.optionsContainer.scrollTop;
         this.renderVisibleOptions(scrollTop, containerHeight);
      });

      this.renderVisibleOptions(0, containerHeight);
   }

   renderVisibleOptions(scrollTop, containerHeight) {
      const startIndex = Math.floor(scrollTop / this.itemHeight);
      const endIndex = Math.ceil(
         (scrollTop + containerHeight) / this.itemHeight,
      );

      this.options.forEach((option, index) => {
         if (index >= startIndex && index <= endIndex) {
            option.style.display = "";
            option.style.position = "absolute";
            option.style.top = `${index * this.itemHeight}px`;
            option.style.left = "0";
            option.style.right = "0";
         } else {
            option.style.display = "none";
         }
      });
   }

   handleSearchKeyboard(e) {
      if (
         e.key === "ArrowDown" ||
         e.key === "ArrowUp" ||
         e.key === "Home" ||
         e.key === "End"
      ) {
         e.preventDefault();
         this.handleKeyboardNavigation(e.key);
      } else if (e.key === "Enter") {
         e.preventDefault();
         if (this.focusedIndex >= 0) {
            const visibleOptions = this.options.filter(
               (opt) => opt.style.display !== "none",
            );
            if (visibleOptions[this.focusedIndex]) {
               visibleOptions[this.focusedIndex].click();
            }
         }
      } else if (e.key === "Escape") {
         this.close();
      }
   }

   handleKeyboard(e) {
      if (e.key === "Enter" || e.key === " ") {
         e.preventDefault();
         this.toggle();
      } else if (e.key === "Escape" && this.isOpen) {
         this.close();
      } else if (
         e.key === "ArrowDown" ||
         e.key === "ArrowUp" ||
         e.key === "Home" ||
         e.key === "End"
      ) {
         e.preventDefault();
         if (!this.isOpen) {
            this.open();
         } else {
            this.handleKeyboardNavigation(e.key);
         }
      }
   }

   handleKeyboardNavigation(key) {
      const visibleOptions = this.options.filter(
         (opt) =>
            opt.style.display !== "none" && opt.dataset.disabled !== "true",
      );

      if (key === "Home") {
         this.focusedIndex = 0;
      } else if (key === "End") {
         this.focusedIndex = visibleOptions.length - 1;
      } else if (key === "ArrowDown") {
         this.focusedIndex = Math.min(
            this.focusedIndex + 1,
            visibleOptions.length - 1,
         );
      } else if (key === "ArrowUp") {
         this.focusedIndex = Math.max(this.focusedIndex - 1, 0);
      }

      this.updateFocusedOption();

      const focusedOption = visibleOptions[this.focusedIndex];
      if (focusedOption) {
         focusedOption.scrollIntoView({ block: "nearest" });
      }
   }

   updateFocusedOption() {
      this.options.forEach((opt, index) => {
         if (index === this.focusedIndex) {
            opt.classList.add("focused");
         } else {
            opt.classList.remove("focused");
         }
      });
   }

   handleOutsideClick(e) {
      if (!this.wrapper.contains(e.target) && this.isOpen) {
         this.close();
      }
   }
}

function initCustomSelects() {
   const wrappers = document.querySelectorAll(".custom-select-wrapper");

   wrappers.forEach((wrapper) => {
      if (!wrapper.dataset.selectInitialized) {
         new CustomSelect(wrapper);
         wrapper.dataset.selectInitialized = "true";
      }
   });
}

if (document.readyState === "loading") {
   document.addEventListener("DOMContentLoaded", initCustomSelects);
} else {
   initCustomSelects();
}

document.addEventListener("astro:page-load", initCustomSelects);
document.addEventListener("astro:after-swap", initCustomSelects);
