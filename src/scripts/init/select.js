/**
 * ОПТИМІЗАЦІЯ ДЛЯ РІЗНИХ РОЗМІРІВ СПИСКІВ
 * ----------------------------------------
 *
 * < 50 елементів:
 * - Базовий селект без додаткових налаштувань
 * - Можна додати пошук для зручності
 *
 * 50-100 елементів:
 * - Обов'язково додайте searchable={true}
 * - Розгляньте sortAlphabetically={true}
 *
 * 100-500 елементів:
 * - searchable={true} + highlightSearch={true}
 * - sortAlphabetically={true}
 * - searchClearable={true}
 *
 * 500-1000 елементів:
 * - Все вище +
 * - Додайте групування якщо можливо
 *
 * 1000+ елементів:
 * - virtualScroll={true} - ОБОВ'ЯЗКОВО!
 * - itemHeight={40} - вкажіть точну висоту
 * - searchable={true}
 * - Уникайте showRemovableTags якщо можливо
 */

